// Every Division I men's basketball program as a fictional school named after
// its campus town ("Lexington Wildcats" for Kentucky), in its 2025-26
// conference. Users can rename everything to make a real-world universe.
//
// Each school: [region, nickname, abbrev, colors x3, state, prestige 1-100].
// Prestige is program pull - recruiting, NIL money, fan interest.

export type CollegeSchool = {
	region: string;
	name: string;
	abbrev: string;
	colors: [string, string, string];
	state: string;
	prestige: number;
};

export type CollegeConference = {
	name: string;
	abbrev: string;
	// Power conferences (and the strongest mid-majors) pay more, draw more and
	// get more NCAA bids. 1 = power, 2 = high-major, 3 = mid-major, 4 = low-major.
	tier: 1 | 2 | 3 | 4;
	schools: CollegeSchool[];
};

type Row = [string, string, string, string, string, string, string, number];

const conf = (
	name: string,
	abbrev: string,
	tier: CollegeConference["tier"],
	rows: Row[],
): CollegeConference => ({
	name,
	abbrev,
	tier,
	schools: rows.map(([region, nickname, ab, c1, c2, c3, state, prestige]) => ({
		region,
		name: nickname,
		abbrev: ab,
		colors: [c1, c2, c3],
		state,
		prestige,
	})),
});

