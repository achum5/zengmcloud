import { assert, describe, test, vi } from "vitest";
import { mockIDBLeague, resetCache, resetG } from "../../../test/helpers.ts";
import { idb } from "../../db/index.ts";
import { g } from "../../util/index.ts";
import { draft } from "../index.ts";
import { DEFAULT_LEVEL } from "../../../common/budgetLevels.ts";
import {
	BODY_KEYS,
	QUANTILES,
	SKILL_KEYS,
	normCdf,
	normInv,
	quantileOf,
	realisticProspect,
	valueAt,
} from "./realisticProspects.ts";
import { REALISTIC_PROSPECTS } from "./realisticProspectsData.ts";
import type { PlayerWithoutKey } from "../../../common/types.ts";

const UNTOUCHED = [...BODY_KEYS, "endu", "oiq", "diq"];

const makeRng = (seed: number) => {
	let s = seed >>> 0;
	return () => {
		s = (s * 1_664_525 + 1_013_904_223) >>> 0;
		return s / 4_294_967_296;
	};
};

const corr = (xs: number[], ys: number[]) => {
	const mean = (vs: number[]) => vs.reduce((a, b) => a + b, 0) / vs.length;
	const mx = mean(xs);
	const my = mean(ys);
	let num = 0;
	let dx = 0;
	let dy = 0;
	for (let i = 0; i < xs.length; i++) {
		num += (xs[i]! - mx) * (ys[i]! - my);
		dx += (xs[i]! - mx) ** 2;
		dy += (ys[i]! - my) ** 2;
	}
	return num / Math.sqrt(dx * dy);
};

describe("realisticProspect", () => {
	test("every table is a usable distribution", () => {
		// Generated by the calibration, so checked rather than trusted: a table
		// that ever goes down, or leaves 0-100, inverts to nonsense.
		const tables = [
			...Object.values(REALISTIC_PROSPECTS.source),
			...Object.values(REALISTIC_PROSPECTS.target),
		];
		for (const table of tables) {
			assert.strictEqual(table.length, QUANTILES.length);
			for (let i = 1; i < table.length; i++) {
				assert.isAtLeast(table[i]!, table[i - 1]!);
			}
			assert.isAtLeast(table[0]!, 0);
			assert.isAtMost(table.at(-1)!, 100);
		}
		for (const spread of REALISTIC_PROSPECTS.spread) {
			assert.isAbove(spread, 0);
		}
	});

	test("the conversions undo each other", () => {
		for (const q of [0.01, 0.2, 0.5, 0.8, 0.99]) {
			assert.closeTo(normCdf(normInv(q)), q, 1e-6);
		}
		// Away from the bottom of the tp table, which is flat at 0 - the
		// non-shooters - so there a value can't say which quantile it came from.
		const table = REALISTIC_PROSPECTS.target.tp;
		for (const q of [0.2, 0.5, 0.8]) {
			assert.closeTo(quantileOf(table, valueAt(table, q)), q, 1e-9);
		}
	});

	const prospect = (overrides: Record<string, number> = {}) =>
		({
			ratings: [
				{
					hgt: 50,
					stre: 40,
					spd: 50,
					jmp: 50,
					endu: 25,
					oiq: 27,
					diq: 27,
					ins: 34,
					dnk: 38,
					ft: 35,
					fg: 35,
					tp: 35,
					drb: 44,
					pss: 41,
					reb: 43,
					...overrides,
				},
			],
		}) as unknown as PlayerWithoutKey;

	test("athleticism and IQ are never touched, and skills stay valid ratings", () => {
		const p = prospect({ tp: 70, ins: 20 });
		realisticProspect(p);
		const ratings = p.ratings[0] as any;
		for (const key of UNTOUCHED) {
			assert.strictEqual(ratings[key], prospect().ratings[0]![key as "hgt"]);
		}
		for (const key of SKILL_KEYS) {
			assert.isTrue(Number.isInteger(ratings[key]), key);
			assert.isAtLeast(ratings[key], 0);
			assert.isAtMost(ratings[key], 100);
		}
	});

	test("a better shooter stays a better shooter", () => {
		// The reshaping moves a prospect along real players' distribution, it
		// doesn't reorder them: with everything else equal, more 3-point shooting
		// in means at least as much out.
		const spy = vi.spyOn(Math, "random").mockReturnValue(0.5);
		try {
			let previous = -1;
			for (let tp = 0; tp <= 100; tp += 5) {
				const p = prospect({ tp });
				realisticProspect(p);
				const out = (p.ratings[0] as any).tp;
				assert.isAtLeast(out, previous, `tp ${tp}`);
				previous = out;
			}
		} finally {
			spy.mockRestore();
		}
	});
});

// Seeded and paired, as in specializedDraftProspects.test.ts: every class is
// drawn from the same stream, so they differ by the settings and nothing else.
const generateClass = async ({
	realistic,
	specialized,
}: {
	realistic: boolean;
	specialized: boolean;
}) => {
	const spy = vi.spyOn(Math, "random").mockImplementation(makeRng(20_261_029));
	try {
		resetG();
		await resetCache();
		idb.league = mockIDBLeague();
		g.setWithoutSavingToDB("realisticDraftProspects", realistic);
		g.setWithoutSavingToDB("specializedDraftProspects", specialized);

		await draft.genPlayers(g.get("season"), DEFAULT_LEVEL);
		const players = await idb.cache.players.indexGetAll(
			"playersByDraftYearRetiredYear",
			[[g.get("season")], [g.get("season"), Infinity]],
		);

		// @ts-expect-error
		idb.league = undefined;

		return players.toSorted((a, b) => a.pid - b.pid);
	} finally {
		spy.mockRestore();
	}
};

const lastRatings = (p: { ratings: unknown[] }) => p.ratings.at(-1) as any;

describe("realisticDraftProspects", () => {
	test("defaults to off, so existing leagues are unchanged", () => {
		resetG();
		assert.strictEqual(g.get("realisticDraftProspects"), false);
	});

	test("only the eight skill ratings change, and the class keeps its size", async () => {
		const normal = await generateClass({
			realistic: false,
			specialized: false,
		});
		const realistic = await generateClass({
			realistic: true,
			specialized: false,
		});
		assert.strictEqual(realistic.length, 70);
		assert.strictEqual(realistic.length, normal.length);

		let skillsChanged = 0;
		for (const [i, p] of realistic.entries()) {
			const before = lastRatings(normal[i]!);
			const after = lastRatings(p);
			assert.strictEqual(p.firstName, normal[i]!.firstName);
			for (const key of UNTOUCHED) {
				assert.strictEqual(after[key], before[key], key);
			}
			if (SKILL_KEYS.some((key) => after[key] !== before[key])) {
				skillsChanged += 1;
			}
		}
		assert.isAbove(skillsChanged, 60);
	});

	test("shooting skills stop moving in lockstep", async () => {
		// The point of the feature: generated 3-point and mid-range shooting
		// share one roll (correlation ~0.8), real players' don't (~0.3).
		const tpFg = (players: { ratings: unknown[] }[]) =>
			corr(
				players.map((p) => lastRatings(p).tp),
				players.map((p) => lastRatings(p).fg),
			);
		const normal = await generateClass({
			realistic: false,
			specialized: false,
		});
		const realistic = await generateClass({
			realistic: true,
			specialized: false,
		});
		assert.isBelow(
			tpFg(realistic),
			tpFg(normal) - 0.25,
			`realistic ${tpFg(realistic).toFixed(2)} vs normal ${tpFg(normal).toFixed(2)}`,
		);
	});

	test("with both reshapings on, realistic replaces specialized rather than stacking", async () => {
		const both = await generateClass({ realistic: true, specialized: true });
		const realistic = await generateClass({
			realistic: true,
			specialized: false,
		});
		for (const [i, p] of both.entries()) {
			for (const key of SKILL_KEYS) {
				assert.strictEqual(
					lastRatings(p)[key],
					lastRatings(realistic[i]!)[key],
					key,
				);
			}
		}
	});
});
