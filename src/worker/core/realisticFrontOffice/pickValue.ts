const TABLE_PICKS = PICK_TABLE.length;
const TABLE_YEARS = PICK_TABLE[0]!.length - 1;

// The player a pick is expected to become, `years` seasons after its draft (1
// is his rookie season), as a roster sees him, and the chance he is on it. `slot` is the pick's place in
// the whole draft, 0 for the first; leagues of another size are read at the
// same fraction of the way through. His synergy is a typical player's of his
// overall: a prospect's skills are not known yet.
export const pickPlayer = ({
	slot,
	numPicks,
	years,
	boom = false,
}: {
	slot: number;
	numPicks: number;
	years: number;
	// The best quarter and the rest (PICK_BOOM), not the halves.
	boom?: boolean;
}): StrengthPlayer & {
	availability: number;
	// The worse and the better half (PICK_HALVES), when there are any.
	halves?: (StrengthPlayer & { availability: number })[];
} => {
	const row = Math.min(
		TABLE_PICKS - 1,
		Math.max(0, Math.round((slot / Math.max(1, numPicks)) * TABLE_PICKS)),
	);
	const year = Math.min(TABLE_YEARS, Math.max(0, years));
	const [roleFree, offense, usage, ovr, kept] = PICK_TABLE[row]![year]!;
	const synergy: SynergyCompositeRating = typicalSynergy(ovr!);
	const halves = PICK_HALVES[row]?.[year];
	const parts = boom ? PICK_BOOM[row]?.[year] : undefined;
	const part = (at: number, availability: number) => ({
		roleFree: parts![at]!,
		offense: parts![at + 1]!,
		usage: parts![at + 2]!,
		synergy: typicalSynergy(parts![at + 3]!),
		guard: TYPICAL_GUARD,
		forward: TYPICAL_FORWARD,
		valueNoPot: parts![at + 3]!,
		availability,
	});
	return {
		roleFree: roleFree!,
		offense: offense!,
		usage: usage!,
		synergy,
		guard: TYPICAL_GUARD,
		forward: TYPICAL_FORWARD,
		valueNoPot: ovr!,
		availability: kept!,
		halves: parts
			? parts[4]! > 0 && parts[9]! > 0
				? [part(0, parts[4]!), part(5, parts[9]!)]
				: undefined
			: halves && halves[8]! > 0
				? [0, 4].map((at) => ({
						roleFree: halves[at]!,
						offense: halves[at + 1]!,
						usage: halves[at + 2]!,
						synergy: typicalSynergy(halves[at + 3]!),
						guard: TYPICAL_GUARD,
						forward: TYPICAL_FORWARD,
						valueNoPot: halves[at + 3]!,
						availability: halves[8]! / 2,
					}))
				: undefined,
	};
};
