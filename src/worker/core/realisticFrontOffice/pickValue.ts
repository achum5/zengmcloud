const TABLE_PICKS = PICK_TABLE.length;
const TABLE_YEARS = PICK_TABLE[0]!.length - 1;

// The player a pick is expected to become, `years` seasons after its draft (1
// is his rookie season), as a roster sees him. `slot` is the pick's place in
// the whole draft, 0 for the first; leagues of another size are read at the
// same fraction of the way through. His synergy is a minimum player's: a
// prospect's skills are not known yet.
export const pickPlayer = ({
	slot,
	numPicks,
	years,
}: {
	slot: number;
	numPicks: number;
	years: number;
}): StrengthPlayer => {
	const row = Math.min(
		TABLE_PICKS - 1,
		Math.max(0, Math.round((slot / Math.max(1, numPicks)) * TABLE_PICKS)),
	);
	const [roleFree, offense, usage, ovr] =
		PICK_TABLE[row]![Math.min(TABLE_YEARS, Math.max(0, years))]!;
	const synergy: SynergyCompositeRating = getReplacement().synergy;
	return {
		roleFree: roleFree!,
		offense: offense!,
		usage: usage!,
		synergy,
		valueNoPot: ovr!,
	};
};
